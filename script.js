function getMatches(){
  const set = userSet();
  return RECIPES.map(r=>{
    const matched = r.need.filter(n=>set.has(n));
    const missing = r.need.filter(n=>!set.has(n));
    const pct = r.need.length ? Math.round(matched.length / r.need.length * 100) : 0;
    return {r, matched, missing, pct};
  }).filter(m=>m.pct > 0);
}

function renderSugg(){
  const box = $("#sugg");
  const q = normKey($("#ingInput").value);
  if(!q){ box.innerHTML = ""; return; }
  const keys = Object.keys(ING)
    .filter(k=>!selected.includes(k) && normKey(k).includes(q))
    .slice(0,9);
  box.innerHTML = keys.map(k=>`<button type="button" data-add="${escapeHTML(k)}">${escapeHTML(em(k))} ${escapeHTML(k)}</button>`).join("");
}

function addIng(name){
  try {
    name = clean(name);
    if(!name) return;
    const official = Object.keys(ING).find(k=>normKey(k) === normKey(name));
    if(official) name = official;
    else if(!ING[name]) ING[name] = "🍽️";

    if(selected.includes(name)) return;
    selected.push(name);
    $("#ingInput").value = "";
    renderSugg();
    updateAll();
  } catch(e) {
    console.warn("خطا در addIng:", e);
  }
}

function renderChips(){
  $("#chips").innerHTML = selected.map(n=>`
    <span class="chip">${escapeHTML(em(n))} ${escapeHTML(n)}<button type="button" data-del="${escapeHTML(n)}" aria-label="حذف ${escapeHTML(n)}">×</button></span>
  `).join("");
  $("#fridgeCount").textContent = faN(selected.length);
  $("#pantryNote").style.display = pantryOn ? "block" : "none";
  $("#clearAll").style.display = selected.length ? "block" : "none";
}

function renderPacks(){
  $("#packs").innerHTML = PACKS.map((p,i)=>`
    <button type="button" data-pack="${i}">${p.icon} ${p.name}</button>
  `).join("");
}

function renderTags(){
  const counts = {};
  RECIPES.forEach(r=>r.cats.forEach(c=>counts[c]=(counts[c]||0)+1));
  const tags = Object.keys(counts).sort((a,b)=>counts[b]-counts[a]);
  $("#tagbar").innerHTML = `<button class="tag active" data-tag="all">همه</button>` +
    tags.map(t=>`<button class="tag" data-tag="${t}">${t} (${faN(counts[t])})</button>`).join("");
}

function renderResults(){
  try {
    const matches = getMatches();
    const full = matches.filter(m=>m.pct === 100);
    const near = matches.filter(m=>m.pct >= 50 && m.pct < 100);
    const low = matches.filter(m=>m.pct < 50);

    $("#cAll").textContent = faN(matches.length);
    $("#cFull").textContent = faN(full.length);
    $("#cNear").textContent = faN(near.length);
    $("#cLow").textContent = faN(low.length);

    $("#stats").textContent = selected.length
      ? `${faN(selected.length)} ماده در یخچال • ${faN(full.length)} غذای کاملاً آماده`
      : "برای شروع، مواد یخچال را اضافه کن.";

    if(!selected.length){
      $("#grid").innerHTML = "";
      $("#empty").style.display = "block";
      $("#empty").innerHTML = `<span class="big">🧊</span>یخچالت هنوز خالی است!<br>از بالا مواد را اضافه کن یا یکی از بسته‌های آماده را بزن.`;
      return;
    }

    let list = curTab === "all" ? matches
      : curTab === "full" ? full
      : curTab === "near" ? near
      : low;

    if(curTag !== "all") list = list.filter(m=>m.r.cats.includes(curTag));

    if(sortMode === "fast"){
      list.sort((a,b)=>a.r.time-b.r.time || b.pct-a.pct);
    } else if(sortMode === "easy"){
      list.sort((a,b)=>a.r.diff-b.r.diff || b.pct-a.pct);
    } else {
      list.sort((a,b)=>b.pct-a.pct || a.missing.length-b.missing.length || a.r.time-b.r.time);
    }

    if(!list.length){
      $("#grid").innerHTML = "";
      $("#empty").style.display = "block";
      $("#empty").innerHTML = `<span class="big">🤔</span>با این فیلتر غذایی پیدا نشد.`;
      return;
    }

    $("#empty").style.display = "none";
    $("#grid").innerHTML = list.map((m,i)=>{
        const cls = m.pct === 100 ? "p-good" : m.pct >= 50 ? "p-mid" : "p-low";
      const missTxt = m.missing.length
        ? "🛒 کم داری: " + m.missing.slice(0,3).join("، ") + (m.missing.length > 3 ? " و " + faN(m.missing.length-3) + " مورد دیگر" : "")
        : "✅ همه مواد لازم را داری!";
      const ribbon = (i===0 && sortMode==="best" && m.pct===100)
        ? `<div class="ribbon">⭐ بهترین پیشنهاد</div>` : "";

      return `
        <article class="card ${m.pct===100 ? "full" : ""}" style="animation-delay:${Math.min(i*35,350)}ms">
          ${ribbon}
          <div class="origin-badge">${m.r.flag || "🌍"} ${m.r.origin || "بین‌المللی"}</div>
          <div class="card-top">
            <div class="bowl">${m.r.emoji}</div>
            <div>
              <h3>${m.r.name}</h3>
              <div class="cats">${m.r.cats.map(c=>`<span>${c}</span>`).join("")}</div>
            </div>
            <div class="pct ${cls}">${faN(m.pct)}٪</div>
          </div>
          <div class="bar"><i style="width:${m.pct}%"></i></div>
          <p class="miss">${missTxt}</p>
          <div class="meta">
            <span>⏱ ${fmtTime(m.r.time)}</span>
            <span>👥 ${faN(m.r.serves)} نفر</span>
            <span>${diffLabel(m.r.diff)}</span>
          </div>
          <button class="btn" data-open="${m.r.id}">${m.pct===100 ? "بپزش! 🍳" : "دستور کامل 👨‍🍳"}</button>
        </article>
      `;
    }).join("");
  } catch(e) {
    console.warn("خطا در renderResults:", e);
  }
}

function openModal(id){
  const r = RECIPES.find(x=>x.id === id);
  if(!r) return;
  const set = userSet();

  const rows = [
    ...r.need.map(n=>({n, opt:false, have:set.has(n)})),
    ...(r.opt||[]).map(n=>({n, opt:true, have:set.has(n)}))
  ];

  const steps = r.instructions.split(/[؛.!؟]+/).map(s=>s.trim()).filter(Boolean)
    .map((s,i)=>`<li><b>${faN(i+1)}</b><span>${s}</span></li>`).join("");

  // تبدیل nutrition به گرید
  const nutritionItems = (r.nutrition || "").split("•").map(s=>s.trim()).filter(Boolean);

  $("#modalBody").innerHTML = `
    <div class="modal-head">
      <div class="bowl">${r.emoji}</div>
      <div>
        <h3 id="modalTitle">${escapeHTML(r.name)} <span style="font-size:0.7rem;color:#7c6a52;">${escapeHTML(r.flag || "")} ${escapeHTML(r.origin || "")}</span></h3>
        <div class="meta-pills">
          <span>⏱ ${fmtTime(r.time)}</span>
          <span>👥 ${faN(r.serves)} نفر</span>
          <span>${diffLabel(r.diff)}</span>
          <span>${r.cats.join(" • ")}</span>
        </div>
      </div>
    </div>

    ${r.history ? `
    <div class="origin-history">
      <strong>📜 داستان غذا:</strong><br>
      ${r.history}
    </div>
    ` : ""}

    <div class="section">
      <h4>🧺 مواد لازم</h4>
      <div class="ings">
        ${rows.map(row=>`
          <div class="ing ${row.opt ? "opt" : row.have ? "have" : "missing"}">
            <span>${em(row.n)} ${row.n}</span>
            <i>${row.opt ? "اختیاری" : row.have ? "موجود" : "کم داری"}</i>
          </div>
        `).join("")}
      </div>
    </div>

    ${nutritionItems.length ? `
    <div class="section">
      <h4>💪 ارزش غذایی (تقریبی)</h4>
      <div class="nutrition-grid">
        ${nutritionItems.map(item=>`<span>${item}</span>`).join("")}
      </div>
    </div>
    ` : ""}

    <div class="section">
      <h4>👨‍🍳 روش پخت</h4>
      <ol class="steps">${steps || "<li>مواد را با سلیقه خود بپزید.</li>"}</ol>
    </div>

    <div class="note">💡 برای نتیجه بهتر، مواد تازه استفاده کن و چاشنی‌ها را مطابق ذائقه تنظیم کن.</div>
  `;

  $("#modal").classList.add("open");
  document.body.style.overflow = "hidden";
}

function closeModal(){
  $("#modal").classList.remove("open");
  document.body.style.overflow = "";
}

function updateAll(){
  renderChips();
  renderResults();
  saveState();
}

