$("#addBtn").addEventListener("click", (e)=>{
  e.preventDefault();
  const val = $("#ingInput").value;
  if(val.trim()) addIng(val);
});

$("#ingInput").addEventListener("keydown", e=>{
  if(e.key === "Enter") {
    e.preventDefault();
    const val = e.target.value;
    if(val.trim()) addIng(val);
  }
});

$("#ingInput").addEventListener("input", renderSugg);

$("#sugg").addEventListener("click", e=>{
  const b = e.target.closest("[data-add]");
  if(b) addIng(b.dataset.add);
});

document.addEventListener("click", e=>{
  if(!e.target.closest(".input-wrap")) $("#sugg").innerHTML = "";
});

$("#chips").addEventListener("click", e=>{
  const b = e.target.closest("[data-del]");
  if(!b) return;
  selected = selected.filter(x=>x !== b.dataset.del);
  updateAll();
});

$("#clearAll").addEventListener("click", ()=>{
  selected = [];
  updateAll();
});

$("#pantryToggle").addEventListener("change", e=>{
  pantryOn = e.target.checked;
  updateAll();
});

$("#packs").addEventListener("click", e=>{
  const b = e.target.closest("[data-pack]");
  if(!b) return;
  const p = PACKS[+b.dataset.pack];
  p.items.forEach(n=>{
    if(!selected.includes(n)) selected.push(n);
  });
  updateAll();
});

$("#tabs").addEventListener("click", e=>{
  const b = e.target.closest("[data-tab]");
  if(!b) return;
  curTab = b.dataset.tab;
  document.querySelectorAll(".tab").forEach(x=>x.classList.toggle("active", x === b));
  renderResults();
});

$("#tagbar").addEventListener("click", e=>{
  const b = e.target.closest("[data-tag]");
  if(!b) return;
  curTag = b.dataset.tag;
  document.querySelectorAll(".tag").forEach(x=>x.classList.toggle("active", x === b));
  renderResults();
});

$("#sortSel").addEventListener("change", e=>{
  sortMode = e.target.value;
  renderResults();
});

$("#grid").addEventListener("click", e=>{
  const b = e.target.closest("[data-open]");
  if(b) openModal(+b.dataset.open);
});

$("#modalClose").addEventListener("click", closeModal);
$("#modal").addEventListener("click", e=>{
  if(e.target === e.currentTarget) closeModal();
});
window.addEventListener("keydown", e=>{
  if(e.key === "Escape") closeModal();
});

