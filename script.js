const clean = s => s.trim().replace(/ي/g,"ی").replace(/ك/g,"ک");
const normKey = s => clean(s).replace(/\u200c/g,"").replace(/\s+/g,"");
const em = n => ING[n] || "🍽️";
const userSet = () => new Set([...selected, ...(pantryOn ? PANTRY : [])]);
const escapeHTML = value => String(value).replace(/[&<>"']/g, ch => ({
  "&":"&amp;", "<":"&lt;", ">":"&gt;", '"':"&quot;", "'":"&#39;"
}[ch]));

const STORAGE_KEY = "chi-bepazam-state-v1";

function saveState(){
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify({selected, pantryOn}));
  } catch(e) {
    console.warn("ذخیره‌سازی محلی در دسترس نیست:", e);
  }
}

function loadState(){
  try {
    const saved = JSON.parse(localStorage.getItem(STORAGE_KEY) || "null");
    if(!saved || typeof saved !== "object") return;

    if(Array.isArray(saved.selected)){
      selected = [...new Set(
        saved.selected
          .filter(x => typeof x === "string")
          .map(clean)
          .filter(Boolean)
      )].slice(0, 100);

      selected.forEach(n => {
        if(!ING[n]) ING[n] = "🍽️";
      });
    }
    if(typeof saved.pantryOn === "boolean") pantryOn = saved.pantryOn;
  } catch(e) {
    console.warn("داده‌های ذخیره‌شده قابل خواندن نیستند:", e);
  }
}

function diffLabel(d){
  return d===1 ? "🟢 آسان" : d===2 ? "🟡 متوسط" : "🔴 حرفه‌ای";
}

function fmtTime(m){
  if(m < 60) return faN(m) + " دقیقه";
  const h = Math.floor(m/60), r = m%60;
  return faN(h) + " ساعت" + (r ? " و " + faN(r) + " دقیقه" : "");
}

